/**
 * Site language: English (en) / Español (es).
 * Stored in cookie scifables_lang; switch via lang-switch.php?lang=es&redirect=…
 */

function i18n_supported_langs(): array
{
    return ['en', 'es'];
}

function i18n_normalize_lang(?string $lang): string
{
    $lang = strtolower(trim((string) $lang));

    return in_array($lang, i18n_supported_langs(), true) ? $lang : 'en';
}

function current_lang(): string
{
    static $lang = null;
    if ($lang !== null) {
        return $lang;
    }

    if (isset($_GET['lang'])) {
        $lang = i18n_normalize_lang((string) $_GET['lang']);
        return $lang;
    }

    $lang = i18n_normalize_lang((string) ($_COOKIE['scifables_lang'] ?? 'en'));

    return $lang;
}

function is_spanish(): bool
{
    return current_lang() === 'es';
}

function set_site_lang(string $lang): void
{
    $lang = i18n_normalize_lang($lang);
    $secure = (!empty($_SERVER['HTTPS']) && $_SERVER['HTTPS'] !== 'off')
        || ((string) ($_SERVER['HTTP_X_FORWARDED_PROTO'] ?? '') === 'https');

    setcookie('scifables_lang', $lang, [
        'expires' => time() + 60 * 60 * 24 * 365,
        'path' => '/',
        'secure' => $secure,
        'httponly' => false,
        'samesite' => 'Lax',
    ]);
    $_COOKIE['scifables_lang'] = $lang;
}

/** Build a same-page URL that switches language. */
function lang_switch_url(string $lang, ?string $redirect = null): string
{
    $lang = i18n_normalize_lang($lang);
    if ($redirect === null || $redirect === '') {
        $redirect = (string) ($_SERVER['REQUEST_URI'] ?? '/');
    }

    return app_url('lang-switch.php?lang=' . rawurlencode($lang) . '&redirect=' . rawurlencode($redirect));
}

/**
 * Translate a UI string key. Falls back to English, then the key itself.
 *
 * @param array<string, string|int|float> $replace
 */
function t(string $key, array $replace = []): string
{
    $catalog = i18n_catalog();
    $lang = current_lang();
    $text = $catalog[$lang][$key] ?? $catalog['en'][$key] ?? $key;

    foreach ($replace as $name => $value) {
        $text = str_replace(':' . $name, (string) $value, $text);
    }

    return $text;
}

/** HTML lang attribute value. */
function html_lang_attr(): string
{
    return current_lang() === 'es' ? 'es' : 'en';
}

