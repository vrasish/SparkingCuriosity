function topic_label(string $slugOrLabel): string
{
    $slugOrLabel = trim($slugOrLabel);
    if ($slugOrLabel === '') {
        return '';
    }

    $key = 'topic.' . $slugOrLabel;
    $translated = t($key);
    if ($translated !== $key) {
        return $translated;
    }

    // Home cards often use ALL CAPS categories (e.g. PLANTS).
    static $canonical = [
        'animals' => 'Animals',
        'chemistry' => 'Chemistry',
        'earth science' => 'Earth Science',
        'engineering' => 'Engineering',
        'human body' => 'Human Body',
        'microbes' => 'Microbes',
        'physical science' => 'Physical Science',
        'plants' => 'Plants',
        'space' => 'Space',
        'weather' => 'Weather',
    ];
    $norm = $canonical[strtolower($slugOrLabel)] ?? null;
    if ($norm !== null) {
        $key = 'topic.' . $norm;
        $translated = t($key);
        if ($translated !== $key) {
            return $translated;
        }
    }

    return $slugOrLabel;
}

/** Localized story-topic chip (e.g. Photosynthesis → Fotosíntesis). */
function story_topic_label(string $topic): string
{
    $topic = trim($topic);
    if ($topic === '') {
        return '';
    }

    $key = 'story_topic.' . $topic;
    $translated = t($key);

    return $translated === $key ? $topic : $translated;
}

function render_language_selector(?string $redirect = null): void
{
    $current = current_lang();
    echo '<div class="lang-switcher" role="group" aria-label="' . e(t('lang.label')) . '">';
    echo '<a href="' . e(lang_switch_url('en', $redirect)) . '" class="lang-switch-btn' . ($current === 'en' ? ' is-active' : '') . '"'
        . ($current === 'en' ? ' aria-current="true"' : '')
        . ' hreflang="en" title="' . e(t('lang.switch_to_english')) . '">EN</a>';
    echo '<a href="' . e(lang_switch_url('es', $redirect)) . '" class="lang-switch-btn' . ($current === 'es' ? ' is-active' : '') . '"'
        . ($current === 'es' ? ' aria-current="true"' : '')
        . ' hreflang="es" title="' . e(t('lang.switch_to_spanish')) . '">ES</a>';
    echo '</div>';
}

